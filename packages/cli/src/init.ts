import { bunExecutable } from '../../shared/src/bun';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { packaged, runtimeFile, projectMcpFile } from './runtime';
import { spawnSync } from 'node:child_process';

/** Configure a supported Vite project without importing its configuration. */
export function initProject(root: string, packageSource?: string) {
  const manifestPath = resolve(root, 'package.json');
  if (
    ['vite.config.cjs', 'vite.config.cts'].some((name) =>
      existsSync(resolve(root, name)),
    )
  )
    throw new Error(
      'CommonJS Vite configs require manual integration; no files changed.',
    );
  let pkg = JSON.parse(readFileSync(manifestPath, 'utf8'));
  if (!pkg.devDependencies?.vite && !pkg.dependencies?.vite)
    throw new Error(
      'This installer currently supports Vite projects. No files changed.',
    );
  const dev = pkg.scripts?.dev;
  const installed =
    typeof dev === 'string' && dev.includes('--config vite.nudge.config.ts');
  if (
    !installed &&
    (typeof dev !== 'string' ||
      !/^vite(?:\s|$)/.test(dev) ||
      /[;&|\r\n]|--config|(?:^|\s)-c(?:\s|$)/.test(dev))
  )
    throw new Error(
      'Expected a direct vite dev script without --config. Configure this project manually; no files changed.',
    );
  const candidates = ['ts', 'mts', 'js', 'mjs']
    .map((ext) => `vite.config.${ext}`)
    .filter((name) => existsSync(resolve(root, name)));
  if (candidates.length > 1)
    throw new Error('Multiple Vite configs found; choose one before setup.');
  const plugin = packaged
    ? 'usenudge/vite'
    : runtimeFile('vite').replaceAll('\\', '/');
  const wrapperPath = resolve(root, 'vite.nudge.config.ts');
  const marker = '// Generated by Nudge local setup.\n';
  if (
    existsSync(wrapperPath) &&
    !readFileSync(wrapperPath, 'utf8').startsWith(marker)
  )
    throw new Error(
      'vite.nudge.config.ts already exists and is not owned by Nudge. No files changed.',
    );
  const wrapper =
    marker +
    `import { mergeConfig } from 'vite';\nimport { nudge } from ${JSON.stringify(plugin)};\n` +
    (candidates[0]
      ? `import original from ${JSON.stringify('./' + candidates[0])};\n`
      : 'const original = {};\n') +
    `export default async (env: import('vite').ConfigEnv) => mergeConfig(await (typeof original === 'function' ? original(env) : original), { plugins: [nudge()] });\n`;
  if (
    packaged &&
    !pkg.devDependencies?.usenudge &&
    !pkg.dependencies?.usenudge
  ) {
    const manager =
      pkg.packageManager?.split('@')[0] ??
      (existsSync(resolve(root, 'pnpm-lock.yaml'))
        ? 'pnpm'
        : existsSync(resolve(root, 'package-lock.json'))
          ? 'npm'
          : existsSync(resolve(root, 'yarn.lock'))
            ? 'yarn'
            : 'bun');
    if (!['bun', 'npm', 'pnpm', 'yarn'].includes(manager))
      throw new Error(
        'Unsupported package manager. Install usenudge as a dev dependency, then rerun init.',
      );
    const executable = manager === 'bun' ? bunExecutable() : Bun.which(manager);
    if (!executable)
      throw new Error(
        `${manager} is not on PATH. Install usenudge as a dev dependency, then rerun init.`,
      );
    const version = JSON.parse(
      readFileSync(
        resolve(dirname(runtimeFile('vite')), '../package.json'),
        'utf8',
      ),
    ).version;
    const source = packageSource ?? `usenudge@${version}`;
    if (source.startsWith('-')) throw new Error('Invalid package source.');
    const result = spawnSync(
      executable,
      [
        manager === 'npm' ? 'install' : 'add',
        manager === 'npm' ? '--save-dev' : '-D',
        source,
      ],
      { cwd: root, stdio: 'inherit', windowsHide: true },
    );
    if (result.status !== 0)
      throw new Error(
        'Dependency installation failed; Vite configuration was not changed. Check package-manager output before retrying.',
      );
    pkg = JSON.parse(readFileSync(manifestPath, 'utf8'));
  }
  if (!installed)
    pkg.scripts.dev = `bun --bun ${dev} --config vite.nudge.config.ts`;
  const ignorePath = resolve(root, '.gitignore');
  const previousIgnore = existsSync(ignorePath)
    ? readFileSync(ignorePath, 'utf8')
    : '';
  const ignore = previousIgnore
    .split(/\r?\n/)
    .filter(
      (line) =>
        line !== 'vite.nudge.config.ts' && line !== '/vite.nudge.config.ts',
    )
    .join('\n');
  // Persistent integration is explicit: commit its portable wrapper with the
  // dev script. Ignoring the wrapper would break a clean checkout's dev command.
  const entries = ['.nudge/'];
  const missing = entries.filter(
    (entry) => !ignore.split(/\r?\n/).includes(entry),
  );
  writeFileSync(wrapperPath, wrapper);
  if (!installed)
    writeFileSync(manifestPath, JSON.stringify(pkg, null, 2) + '\n');
  if (missing.length || ignore !== previousIgnore)
    writeFileSync(
      ignorePath,
      ignore +
        (ignore.endsWith('\n') || !ignore ? '' : '\n') +
        missing.join('\n') +
        '\n',
    );
  mkdirSync(resolve(root, '.nudge'), { recursive: true, mode: 0o700 });
  writeFileSync(
    resolve(root, '.nudge/mcp-config.json'),
    JSON.stringify(
      {
        mcpServers: {
          usenudge: {
            command: bunExecutable(),
            args: [projectMcpFile(root)],
            env: { NUDGE_PROJECT_ROOT: root },
          },
        },
      },
      null,
      2,
    ) + '\n',
    { mode: 0o600 },
  );
  console.log(
    packaged
      ? 'Nudge configured. Run your usual dev script.'
      : 'Nudge configured. Run your usual dev script. Local checkout must remain available; no packages were downloaded.',
  );
  console.log(
    'Optional external agent integration: project-specific MCP configuration is in .nudge/mcp-config.json.',
  );
}
