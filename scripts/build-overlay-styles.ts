import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

export function buildOverlayStyles() {
  const root = resolve(import.meta.dir, '..');
  const output = resolve(root, 'packages/overlay/dist');
  mkdirSync(output, { recursive: true });
  const result = spawnSync(
    process.execPath,
    [
      '--bun',
      resolve(root, 'node_modules/.bin/tailwindcss'),
      '-i',
      resolve(root, 'packages/overlay/src/styles.css'),
      '-o',
      resolve(output, 'styles.css'),
      '--minify',
    ],
    { cwd: root, encoding: 'utf8' },
  );
  if (result.status !== 0) throw new Error(result.stdout + result.stderr);
  let css = readFileSync(resolve(output, 'styles.css'), 'utf8');
  // Chromium does not register @property rules inside shadow stylesheets.
  // Initialize Tailwind's non-inheriting properties on each shadow element so
  // a popup's translate/ring variables cannot leak into its child controls.
  const initial = [
    ...css.matchAll(/@property\s+(--tw-[\w-]+)\s*\{([^}]+)\}/g),
  ].flatMap((match) => {
    const value = match[2]!.match(/initial-value:\s*([^;}]*)/);
    return value ? [`${match[1]}:${value[1]}`] : [];
  });
  css += `\n@layer properties { :host, *, ::before, ::after { ${initial.join(';')} } }`;
  writeFileSync(resolve(output, 'styles.css'), css);
  const modulePath = resolve(output, 'styles.ts');
  const source = `// Generated by scripts/build-overlay-styles.ts.\nexport const css = ${JSON.stringify(css)};\n`;
  if (!existsSync(modulePath) || readFileSync(modulePath, 'utf8') !== source)
    writeFileSync(modulePath, source);
}
if (import.meta.main) buildOverlayStyles();
